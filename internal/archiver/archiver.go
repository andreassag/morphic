// ArchiveRequest defines parameters for bundling files.
type ArchiveRequest struct {
	SourcePaths    []string `json:"source_paths"`
	DestinationDir string   `json:"destination_dir"`
	ArchiveName    string   `json:"archive_name"`
	Format         string   `json:"format"` // "zip", "tar.gz", "7z"
	Level          string   `json:"level"`  // "store", "fast", "normal", "best"
	SplitSizeMB    int64    `json:"split_size_mb"`
}

// ArchiverJob tracks background compression progress.
type ArchiverJob struct {
	mu           sync.RWMutex
	shared.Job
	CreatedFiles []string `json:"created_files"`
	TotalBytes   int64    `json:"total_bytes"`
}

// SetBytesWritten updates the total bytes written in a thread-safe manner.
func (j *ArchiverJob) SetBytesWritten(written int64) {
	j.mu.Lock()
	defer j.mu.Unlock()
	j.TotalBytes = written
}

// SetDone marks the job as done and records created files.
func (j *ArchiverJob) SetDone(files []string) {
	j.mu.Lock()
	defer j.mu.Unlock()
	j.Status = shared.JobStatusDone
	j.Progress = 1.0
	j.CreatedFiles = files
	j.DoneAt = time.Now()
}

// SetFailed marks the job as failed with an error message.
func (j *ArchiverJob) SetFailed(errMsg string) {
	j.mu.Lock()
	defer j.mu.Unlock()
	j.Status = shared.JobStatusFailed
	j.Error = errMsg
	j.DoneAt = time.Now()
}

// Snapshot returns a thread-safe copy of the job's state.
func (j *ArchiverJob) Snapshot() ArchiverJob {
	j.mu.RLock()
	defer j.mu.RUnlock()
	var filesCopy []string
	if j.CreatedFiles != nil {
		filesCopy = make([]string, len(j.CreatedFiles))
		copy(filesCopy, j.CreatedFiles)
	}
	return ArchiverJob{
		Job:          j.Job,
		CreatedFiles: filesCopy,
		TotalBytes:   j.TotalBytes,
	}
}

var jobs = shared.NewJobStore[ArchiverJob]()

// GetJob retrieves an archiver job by ID.
func GetJob(id string) (*ArchiverJob, bool) {
	return jobs.Get(id)
}

// SetJob stores an archiver job by ID.
func SetJob(id string, job *ArchiverJob) {
	jobs.Set(id, job)
}

// RegisterCancel registers a cancel func.
func RegisterCancel(id string, cancel context.CancelFunc) {
	jobs.RegisterCancel(id, cancel)
}

// CancelJob cancels an archiver job.
func CancelJob(id string) bool {
	return jobs.Cancel(id)
}

// StartCleanup periodically cleans up expired jobs.
func StartCleanup(ctx context.Context, ttl time.Duration) {
	jobs.StartCleanup(ctx, ttl, func(j *ArchiverJob) time.Time {
		return j.DoneAt
	})
}

// SplitWriter splits output stream across multiple numbered files when byte limit is reached.
type SplitWriter struct {
	basePath     string
	maxBytes     int64
	currentPart  int
	currentBytes int64
	currentFile  *os.File
	createdFiles []string
}

// NewSplitWriter initializes a new SplitWriter.
func NewSplitWriter(basePath string, splitSizeMB int64) (*SplitWriter, error) {
	var maxBytes int64
	if splitSizeMB > 0 {
		maxBytes = splitSizeMB * 1024 * 1024
	}

	sw := &SplitWriter{
		basePath:    basePath,
		maxBytes:    maxBytes,
		currentPart: 1,
	}

	if err := sw.openNextPart(); err != nil {
		return nil, err
	}
	return sw, nil
}

func (sw *SplitWriter) openNextPart() error {
	if sw.currentFile != nil {
		_ = sw.currentFile.Close()
	}

	var partPath string
	if sw.maxBytes <= 0 {
		partPath = sw.basePath
	} else {
		partPath = fmt.Sprintf("%s.%03d", sw.basePath, sw.currentPart)
	}

	f, err := os.OpenFile(partPath, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o644)
	if err != nil {
		return fmt.Errorf("create archive part file %s: %w", partPath, err)
	}

	sw.currentFile = f
	sw.currentBytes = 0
	sw.createdFiles = append(sw.createdFiles, partPath)
	sw.currentPart++
	return nil
}

// Write writes data to current part, rolling over if maxBytes is reached.
func (sw *SplitWriter) Write(p []byte) (int, error) {
	if sw.maxBytes <= 0 {
		return sw.currentFile.Write(p)
	}

	totalWritten := 0
	for len(p) > 0 {
		remaining := sw.maxBytes - sw.currentBytes
		if remaining <= 0 {
			if err := sw.openNextPart(); err != nil {
				return totalWritten, err
			}
			remaining = sw.maxBytes
		}

		toWrite := int64(len(p))
		if toWrite > remaining {
			toWrite = remaining
		}

		n, err := sw.currentFile.Write(p[:toWrite])
		totalWritten += n
		sw.currentBytes += int64(n)
		p = p[n:]
		if err != nil {
			return totalWritten, err
		}
	}
	return totalWritten, nil
}

// Close closes the active file in SplitWriter.
func (sw *SplitWriter) Close() error {
	if sw.currentFile != nil {
		err := sw.currentFile.Close()
		sw.currentFile = nil
		return err
	}
	return nil
}

// CreatedFiles returns the list of files generated by SplitWriter.
func (sw *SplitWriter) CreatedFiles() []string {
	return sw.createdFiles
}

// CreateArchive creates an archive according to request specs.
func CreateArchive(ctx context.Context, req ArchiveRequest, onProgress func(written, total int64)) ([]string, error) {
	select {
	case <-ctx.Done():
		return nil, ctx.Err()
	default:
	}

	destDir, err := shared.ValidateSafeDirPath(req.DestinationDir)
	if err != nil {
		return nil, fmt.Errorf("validate destination directory: %w", err)
	}

	archiveName := req.ArchiveName
	if archiveName == "" {
		archiveName = fmt.Sprintf("archive_%d", time.Now().Unix())
	}
	archiveName = strings.TrimSpace(archiveName)

	format := strings.ToLower(req.Format)
	if format == "" {
		format = "zip"
	}

	var validSources []string
	for _, src := range req.SourcePaths {
		if safe, err := shared.ValidateSafePath(src); err == nil {
			validSources = append(validSources, safe)
		}
	}
	if len(validSources) == 0 {
		return nil, fmt.Errorf("no valid source paths provided")
	}

	// 7z format handled via CLI if available
	if format == "7z" {
		candidates := shared.SevenZipCandidates()
		if len(candidates) == 0 {
			return nil, fmt.Errorf("7z CLI not installed on host")
		}
		bin := candidates[0]
		targetArchive := filepath.Join(destDir, archiveName+".7z")
		args := []string{"a", "-y"}

		switch strings.ToLower(req.Level) {
		case "store":
			args = append(args, "-mx=0")
		case "fast":
			args = append(args, "-mx=1")
		case "best":
			args = append(args, "-mx=9")
		default:
			args = append(args, "-mx=5")
		}

		if req.SplitSizeMB > 0 {
			args = append(args, fmt.Sprintf("-v%dm", req.SplitSizeMB))
		}

		args = append(args, shared.PathForBin(bin, targetArchive))
		for _, s := range validSources {
			args = append(args, shared.PathForBin(bin, s))
		}

		cmd := exec.CommandContext(ctx, bin, args...)
		if out, err := cmd.CombinedOutput(); err != nil {
			return nil, fmt.Errorf("7z archive creation failed: %w (output: %s)", err, string(out))
		}

		matches, _ := filepath.Glob(targetArchive + "*")
		if len(matches) == 0 {
			matches = []string{targetArchive}
		}
		return matches, nil
	}

	switch format {
	case "tar.gz", "tgz":
		return createTarGz(ctx, validSources, filepath.Join(destDir, archiveName+".tar.gz"), req.Level, req.SplitSizeMB, onProgress)
	case "zip":
		fallthrough
	default:
		return createZip(ctx, validSources, filepath.Join(destDir, archiveName+".zip"), req.Level, req.SplitSizeMB, onProgress)
	}
}

type countingWriter struct {
	w       io.Writer
	written int64
}

func (cw *countingWriter) Write(p []byte) (int, error) {
	n, err := cw.w.Write(p)
	atomic.AddInt64(&cw.written, int64(n))
	return n, err
}

func createZip(ctx context.Context, sources []string, outBase string, level string, splitMB int64, onProgress func(written, total int64)) ([]string, error) {
	sw, err := NewSplitWriter(outBase, splitMB)
	if err != nil {
		return nil, err
	}
	defer sw.Close()

	cw := &countingWriter{w: sw}
	zw := zip.NewWriter(cw)

	var zipMethod uint16 = zip.Deflate
	var flateLevel int = flate.DefaultCompression
	switch strings.ToLower(level) {
	case "store":
		zipMethod = zip.Store
	case "fast":
		flateLevel = flate.BestSpeed
	case "best":
		flateLevel = flate.BestCompression
	default:
		flateLevel = flate.DefaultCompression
	}

	if zipMethod == zip.Deflate {
		zw.RegisterCompressor(zip.Deflate, func(out io.Writer) (io.WriteCloser, error) {
			return flate.NewWriter(out, flateLevel)
		})
	}

	for _, src := range sources {
		select {
		case <-ctx.Done():
			return nil, ctx.Err()
		default:
		}

		info, err := os.Stat(src)
		if err != nil {
			continue
		}

		if !info.IsDir() {
			if err := addFileToZip(ctx, zw, src, filepath.Base(src), zipMethod); err != nil {
				return nil, err
			}
			if onProgress != nil {
				onProgress(atomic.LoadInt64(&cw.written), 0)
			}
			continue
		}

		baseDir := filepath.Dir(src)
		err = filepath.WalkDir(src, func(p string, d os.DirEntry, walkErr error) error {
			if walkErr != nil {
				return nil
			}
			select {
			case <-ctx.Done():
				return ctx.Err()
			default:
			}
			if d.IsDir() {
				return nil
			}
			rel, _ := filepath.Rel(baseDir, p)
			if err := addFileToZip(ctx, zw, p, rel, zipMethod); err != nil {
				return err
			}
			if onProgress != nil {
				onProgress(atomic.LoadInt64(&cw.written), 0)
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}

	if err := zw.Close(); err != nil {
		return nil, fmt.Errorf("closing zip writer: %w", err)
	}
	if err := sw.Close(); err != nil {
		return nil, fmt.Errorf("closing split writer: %w", err)
	}

	return sw.CreatedFiles(), nil
}

func addFileToZip(ctx context.Context, zw *zip.Writer, filePath, zipRelPath string, method uint16) error {
	info, err := os.Stat(filePath)
	if err != nil {
		return fmt.Errorf("stat %s: %w", filePath, err)
	}

	header, err := zip.FileInfoHeader(info)
	if err != nil {
		return fmt.Errorf("header for %s: %w", filePath, err)
	}
	header.Name = filepath.ToSlash(zipRelPath)
	header.Method = method

	w, err := zw.CreateHeader(header)
	if err != nil {
		return fmt.Errorf("create zip header %s: %w", zipRelPath, err)
	}

	f, err := os.Open(filePath)
	if err != nil {
		return fmt.Errorf("open file %s: %w", filePath, err)
	}
	defer f.Close()

	buf := make([]byte, 64*1024)
	for {
		select {
		case <-ctx.Done():
			return ctx.Err()
		default:
		}
		n, rErr := f.Read(buf)
		if n > 0 {
			if _, wErr := w.Write(buf[:n]); wErr != nil {
				return fmt.Errorf("write zip stream: %w", wErr)
			}
		}
		if rErr == io.EOF {
			break
		}
		if rErr != nil {
			return fmt.Errorf("read %s: %w", filePath, rErr)
		}
	}
	return nil
}

func createTarGz(ctx context.Context, sources []string, outBase string, level string, splitMB int64, onProgress func(written, total int64)) ([]string, error) {
	sw, err := NewSplitWriter(outBase, splitMB)
	if err != nil {
		return nil, err
	}
	defer sw.Close()

	cw := &countingWriter{w: sw}
	var gzLevel int
	switch strings.ToLower(level) {
	case "store":
		gzLevel = gzip.NoCompression
	case "fast":
		gzLevel = gzip.BestSpeed
	case "best":
		gzLevel = gzip.BestCompression
	default:
		gzLevel = gzip.DefaultCompression
	}

	gw, err := gzip.NewWriterLevel(cw, gzLevel)
	if err != nil {
		return nil, fmt.Errorf("create gzip writer: %w", err)
	}
	tw := tar.NewWriter(gw)

	for _, src := range sources {
		select {
		case <-ctx.Done():
			return nil, ctx.Err()
		default:
		}

		info, err := os.Stat(src)
		if err != nil {
			continue
		}

		if !info.IsDir() {
			if err := addFileToTar(ctx, tw, src, filepath.Base(src)); err != nil {
				return nil, err
			}
			if onProgress != nil {
				onProgress(atomic.LoadInt64(&cw.written), 0)
			}
			continue
		}

		baseDir := filepath.Dir(src)
		err = filepath.WalkDir(src, func(p string, d os.DirEntry, walkErr error) error {
			if walkErr != nil {
				return nil
			}
			select {
			case <-ctx.Done():
				return ctx.Err()
			default:
			}
			if d.IsDir() {
				return nil
			}
			rel, _ := filepath.Rel(baseDir, p)
			if err := addFileToTar(ctx, tw, p, rel); err != nil {
				return err
			}
			if onProgress != nil {
				onProgress(atomic.LoadInt64(&cw.written), 0)
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}

	if err := tw.Close(); err != nil {
		return nil, fmt.Errorf("close tar writer: %w", err)
	}
	if err := gw.Close(); err != nil {
		return nil, fmt.Errorf("close gzip writer: %w", err)
	}
	if err := sw.Close(); err != nil {
		return nil, fmt.Errorf("close split writer: %w", err)
	}

	return sw.CreatedFiles(), nil
}

func addFileToTar(ctx context.Context, tw *tar.Writer, filePath, tarRelPath string) error {
	info, err := os.Stat(filePath)
	if err != nil {
		return fmt.Errorf("stat %s: %w", filePath, err)
	}

	header, err := tar.FileInfoHeader(info, "")
	if err != nil {
		return fmt.Errorf("tar header for %s: %w", filePath, err)
	}
	header.Name = filepath.ToSlash(tarRelPath)

	if err := tw.WriteHeader(header); err != nil {
		return fmt.Errorf("write tar header: %w", err)
	}

	f, err := os.Open(filePath)
	if err != nil {
		return fmt.Errorf("open %s: %w", filePath, err)
	}
	defer f.Close()

	buf := make([]byte, 64*1024)
	for {
		select {
		case <-ctx.Done():
			return ctx.Err()
		default:
		}
		n, rErr := f.Read(buf)
		if n > 0 {
			if _, wErr := tw.Write(buf[:n]); wErr != nil {
				return fmt.Errorf("write tar stream: %w", wErr)
			}
		}
		if rErr == io.EOF {
			break
		}
		if rErr != nil {
			return fmt.Errorf("read %s: %w", filePath, rErr)
		}
	}
	return nil
}
